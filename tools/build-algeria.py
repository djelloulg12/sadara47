"""Builds the Algerian wilaya and commune lists the registration form offers.

Algeria reorganised its territorial divisions in April 2026 (Law 26-06, Journal
Officiel no. 25): eleven districts became wilayas, taking the country from 58 to
69. So the old 58-wilaya lists circulating online are two years out of date, and a
form offering them would send people to a wilaya that no longer exists.

Both lists come from the same source, the 69-wilaya structure published under that
law, and are checked against each other here: the communes must total 1,541 and
every commune must belong to a wilaya that is in the list. A mismatch means the
source changed shape and the form would offer a commune under the wrong wilaya --
exactly the kind of error this is meant to remove -- so the build stops.

The names are taken from the file as they stand. They are never retyped here.

    python tools/build-algeria.py            build from the published source
    python tools/build-algeria.py --check    verify what is already in the repo

Output, both under istimara/:
    algeria.js   the 69 wilayas, small enough to travel with the page
    communes.json  the 1,541 communes grouped by wilaya code, fetched only once a
                   person has actually chosen a wilaya
"""
import io
import json
import os
import sys
from urllib.request import urlopen

ROOT = os.environ.get("SADARA_ROOT") or os.getcwd()

SOURCE = ("https://raw.githubusercontent.com/islam-re/Algeria-wilayas/main/"
          "json/wilaya-commune/wilaya-commune.json")

EXPECTED_WILAYAS = 69
EXPECTED_COMMUNES = 1541

# The club is in Ghardaia, so the form opens there rather than on the first
# wilaya in the list. Its code is fixed here after being read out of the built
# file, never guessed.
HOME_WILAYA = "غرداية"


def load(source_url):
    with urlopen(source_url, timeout=90) as fh:
        raw = fh.read().decode("utf-8")
    return json.loads(raw)


def build(data):
    """Turns the published structure into the two files the page loads.

    French names are dropped: the form is in Arabic, and nothing on it is searched
    by a Latin name. Keeping them would roughly double the download for a word no
    one on this form reads.
    """
    wilayas = []
    communes = {}
    seen = set()
    total = 0

    for w in data:
        name = (w.get("arabic") or "").strip()
        code = str(w.get("code") or "").zfill(2)
        if not name or not code:
            raise SystemExit("a wilaya has no name or no code: %r" % (w,))
        if name in seen:
            raise SystemExit("wilaya listed twice: " + name)
        seen.add(name)

        names = []
        for c in w.get("communes") or []:
            cn = (c.get("arabic") or "").strip()
            if cn:
                names.append(cn)
        # Sorted so the list reads the same on every device and every reload; a
        # select the club used yesterday and one it uses today should match.
        names = sorted(set(names))
        total += len(names)

        wilayas.append({"code": code, "name": name})
        communes[code] = names

    wilayas.sort(key=lambda w: int(w["code"]))

    if len(wilayas) != EXPECTED_WILAYAS:
        raise SystemExit("expected %d wilayas, the source has %d -- the list changed"
                         % (EXPECTED_WILAYAS, len(wilayas)))
    if total != EXPECTED_COMMUNES:
        raise SystemExit("expected %d communes, the source has %d -- the list changed"
                         % (EXPECTED_COMMUNES, total))

    if not any(w["name"] == HOME_WILAYA for w in wilayas):
        raise SystemExit("the club's own wilaya is not in the list: " + HOME_WILAYA)

    header = (
        "/* The %d wilayas of Algeria and their %d communes, as reorganised by Law\n"
        "   26-06 of 4 April 2026 (Journal Officiel no. 25).\n\n"
        "   Generated by tools/build-algeria.py from the published structure. Do not\n"
        "   edit by hand: run the tool again instead, so the list keeps coming from\n"
        "   one source and cannot drift into two.\n\n"
        "   Arabic names only. French names were dropped -- the form is in Arabic and\n"
        "   nothing on it is searched by a Latin name. */\n"
        % (len(wilayas), total)
    )
    js = (header + "window.SADARA_WILAYAS = "
          + json.dumps(wilayas, ensure_ascii=False, indent=0).replace("\n", "")
          + ";\n")
    return js, json.dumps(communes, ensure_ascii=False, separators=(",", ":")), wilayas


def write_files(js, communes_json):
    a = os.path.join(ROOT, "istimara", "algeria.js")
    c = os.path.join(ROOT, "istimara", "communes.json")
    io.open(a, "w", encoding="utf-8", newline="\n").write(js)
    io.open(c, "w", encoding="utf-8", newline="\n").write(communes_json)
    return a, c


def check():
    """Reads back what is in the repo and holds it to the same two numbers."""
    a = os.path.join(ROOT, "istimara", "algeria.js")
    c = os.path.join(ROOT, "istimara", "communes.json")
    for p in (a, c):
        if not os.path.isfile(p):
            print("missing: " + os.path.relpath(p, ROOT))
            return 1
    js = io.open(a, encoding="utf-8").read()
    communes = json.loads(io.open(c, encoding="utf-8").read())

    start = js.index("=") + 1
    wilayas = json.loads(js[start:js.rindex(";")])
    total = sum(len(v) for v in communes.values())
    covered = set(communes)

    problems = []
    if len(wilayas) != EXPECTED_WILAYAS:
        problems.append("wilayas: %d, expected %d" % (len(wilayas), EXPECTED_WILAYAS))
    if total != EXPECTED_COMMUNES:
        problems.append("communes: %d, expected %d" % (total, EXPECTED_COMMUNES))
    # A wilaya with no communes would leave the person with an empty dropdown and
    # nothing to pick -- the exact failure this is meant to stop.
    empty = [w["name"] for w in wilayas if not communes.get(w["code"])]
    if empty:
        problems.append("wilayas with no communes: " + ", ".join(empty))
    orphan = sorted(covered - {w["code"] for w in wilayas})
    if orphan:
        problems.append("commune groups for codes that are not wilayas: " + ", ".join(orphan))

    print("wilayas : %d" % len(wilayas))
    print("communes: %d in %d wilayas" % (total, len(covered)))
    print("the club's wilaya %s is code %s"
          % (HOME_WILAYA, next((w["code"] for w in wilayas if w["name"] == HOME_WILAYA), "?")))
    for p in problems:
        print("PROBLEM: " + p)
    return 1 if problems else 0


if __name__ == "__main__":
    if "--check" in sys.argv:
        raise SystemExit(check())
    js, communes_json, wilayas = build(load(SOURCE))
    a, c = write_files(js, communes_json)
    print("wrote %s (%d wilayas)" % (os.path.relpath(a, ROOT), len(wilayas)))
    print("wrote %s (%d communes, %d bytes)"
          % (os.path.relpath(c, ROOT), sum(len(v) for v in json.loads(communes_json).values()),
             os.path.getsize(c)))
    raise SystemExit(check())
